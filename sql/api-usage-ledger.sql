-- Yacht Logistics OS — API usage ledger setup
-- Safe to run more than once.

create table if not exists public.api_usage (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),

  provider text not null
    check (provider in ('openai', 'groq', 'gemini')),
  model text not null,
  worker_name text not null,
  task_type text,
  provider_request_id text,

  input_tokens bigint not null default 0
    check (input_tokens >= 0),
  output_tokens bigint not null default 0
    check (output_tokens >= 0),
  total_tokens bigint not null default 0
    check (total_tokens >= 0),
  web_search_calls integer not null default 0
    check (web_search_calls >= 0),

  estimated_cost_usd numeric(14, 8) not null default 0
    check (estimated_cost_usd >= 0),
  billed_cost_usd numeric(14, 8)
    check (billed_cost_usd is null or billed_cost_usd >= 0),

  usage_source text not null default 'actual'
    check (usage_source in ('actual', 'estimated', 'provider_reconciled')),
  is_estimated boolean not null default false,
  status text not null default 'completed'
    check (status in ('completed', 'failed', 'skipped')),
  error_code text,
  detail jsonb not null default '{}'::jsonb
);

create index if not exists api_usage_created_at_idx
  on public.api_usage (created_at desc);

create index if not exists api_usage_provider_created_at_idx
  on public.api_usage (provider, created_at desc);

create index if not exists api_usage_worker_created_at_idx
  on public.api_usage (worker_name, created_at desc);

create unique index if not exists api_usage_provider_request_unique_idx
  on public.api_usage (provider, provider_request_id)
  where provider_request_id is not null;

alter table public.api_usage enable row level security;

drop policy if exists "Authenticated users can read API usage"
  on public.api_usage;

create policy "Authenticated users can read API usage"
  on public.api_usage
  for select
  to authenticated
  using (true);

revoke all on table public.api_usage from anon;
revoke all on table public.api_usage from authenticated;
grant select on table public.api_usage to authenticated;

